export type EfaVersion = 'EFAv1' | 'EFAv2' | 'EFAv3' | 'EFAv4';
export type NitroVersion = 'v3' | 'v4' | 'v5' | 'v6';
export type RdmaSupport = 'read + write' | 'read only' | 'none';
export type InstanceCategory = 'gpu' | 'trainium' | 'hpc' | 'general';

export interface InstanceInfo {
  family: string;
  type: string;
  accelerator: string;
  /** Network cards that can carry an EFA or EFA-only interface. One EFA per card. */
  efaInterfaces: number;
  /** Maximum EFA bandwidth in Gbps, aggregate across all EFA interfaces. */
  bandwidthGbps: number;
  efaVersion: EfaVersion;
  nitroVersion: NitroVersion;
  rdma: RdmaSupport;
  useCase: string;
  generation: 'Current' | 'Previous';
  category: InstanceCategory;
  /** Short caveat rendered under the instance type. Only where a number needs one. */
  note?: string;
  provenance: Provenance;
  doc: DocRef;
  /** Populated only for doc-code-conflict rows. */
  conflict?: string;
}

